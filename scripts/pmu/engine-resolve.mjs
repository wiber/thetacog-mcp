// resolveChip(): resolveChip is "find THIS host's chip" (its checkout branch trusts existsSync alone,
// correct only because a checkout binary is always built locally for the host running it) — it has no
// use for an ARBITRARY platform-arch. resolveCrate generalises the exact same three candidates
// (package → checkout → PMU_BINARY) by header-checking all three against the ASKED-FOR platform-arch,
// which resolveChip's checkout branch does not do — the composition a cross-host resolver needs and
// resolveChip was never asked to provide.
//
// ONLY ROUTE TO NAPI WHERE IT COMPUTES THE SAME OUTPUT (data/vna/linux-fallback-inventory.json, C574,
// is the ledger). Per the chair's read of it: --card, --sign and --ballistic are napi-covered with
// byte-identity confirmed in lib.rs; --lens is NOT (the on-chip walker's own --lens runs its own
// gzip-NCD + definer-walk + ratchet pipeline, while napi lens() is the simpler embedded-vocabulary
// placement — never present one as the other's reading). THE ONE DEMONSTRATED READING below,
// ballisticReading(), uses --ballistic because .thetacog/pmu/src/main.rs's run_ballistic and
// ../IntentGuard/napi/src/lib.rs's walk() both call the SAME crate function (`use intentguard::{…,
// ballistic, …}` in main.rs; `intentguard::walk(&g, start_idx, &opts)` in lib.rs) — one engine, two
// doors, never a reimplementation. A flag the inventory has NOT judged covered gets no napi route
// here: a caller asking this module for one of those gets js-fallback named UNMEASURED, never an
// invented answer.
import { existsSync } from 'node:fs';
import { createRequire } from 'node:module';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { binaryPlatform, PKG_CHIP_REL, CHECKOUT_CHIP_REL } from '../vna/recompute-receipt.mjs';
import { resolvePmuBinary } from '../../src/lib/pmu/pmu-binary.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
// scripts/pmu → the repo/package root (same two-up convention ../vna/recompute-receipt.mjs's own
// PKG_ROOT/REPO use — both collapse to this value in the dev checkout; VNA_REPO overrides for a test
// or a bundled copy running somewhere else).
export const PKG_ROOT = resolve(HERE, '..', '..');
export const REPO = process.env.VNA_REPO || resolve(HERE, '..', '..');
// PKG_CHIP_REL/CHECKOUT_CHIP_REL are ../vna/recompute-receipt.mjs's OWN relative paths to the on-chip
// binary (package copy, checkout copy) — imported, never re-spelled, so this module names the binary
// exactly once in the whole scripts/pmu/ tree (that file lives under scripts/vna/, outside this
// directory's own direct-caller ledger, tests/pmu-simulator/one-pipeline.test.mjs).
export const INTENTGUARD_ROOT = (repo = REPO) => process.env.INTENTGUARD_REPO || resolve(repo, '..', 'IntentGuard');

export const ENGINES = Object.freeze({ CRATE: 'crate', NAPI: 'napi', JS_FALLBACK: 'js-fallback' });

const require_ = createRequire(import.meta.url);

/** "intentguard.<platform>-<arch>.node" — the SAME filename src/lib/intentguard/addon.mjs's
 *  addonFileName() and packages/thetacog-mcp-vscode's nativeAddon.ts addonFileName() already spell. */
export function napiFileName(platform = process.platform, arch = process.arch) {
  return `intentguard.${platform}-${arch}.node`;
}

function runsHere(hdr, platform, arch) {
  if (!hdr) return false;
  const [p, archesCsv] = hdr.split('-');
  return p === platform && archesCsv.split(',').includes(arch);
}

/** the on-chip binary whose OWN header matches platform-arch — never its filename, never trusted
 *  by existence alone (see the note above on why this is not resolveChip). null when none does. */
export function resolveCrate({ platform = process.platform, arch = process.arch, pkgRoot = PKG_ROOT, repo = REPO, env = process.env } = {}) {
  const pkgBin = resolve(pkgRoot, PKG_CHIP_REL);
  if (existsSync(pkgBin) && runsHere(binaryPlatform(pkgBin), platform, arch)) return { path: pkgBin, source: 'package' };
  const coBin = resolve(repo, CHECKOUT_CHIP_REL);
  if (existsSync(coBin) && runsHere(binaryPlatform(coBin), platform, arch)) return { path: coBin, source: 'checkout' };
  const envBin = env.PMU_BINARY || env.PMU_ONCHIP || '';
  if (envBin && existsSync(envBin) && runsHere(binaryPlatform(envBin), platform, arch)) return { path: envBin, source: 'PMU_BINARY' };
  return null;
}

/** the IntentGuard napi prebuild for platform-arch, by the shared filename convention. null when absent. */
export function resolveNapi({ platform = process.platform, arch = process.arch, repo = REPO, intentGuardRoot = INTENTGUARD_ROOT(repo), require: req = require_ } = {}) {
  const file = resolve(intentGuardRoot, 'napi', 'dist', napiFileName(platform, arch));
  if (existsSync(file)) return { path: file, source: 'checkout' };
  return resolveInstalledNapi({ platform, arch, require: req });
}

/**
 * C601 — THE NPX PATH FINDS THE ADDON. resolveNapi's checkout branch (INTENTGUARD_REPO env, or the
 * sibling ../IntentGuard checkout) is a dev-tree convenience an `npx thetacog-mcp` install never has
 * — no sibling, no env var. Since packages/thetacog-mcp now depends on "intentguard": "^2.0.0"
 * (package.json), the published tarball's own node_modules/intentguard carries the SAME four
 * napi/dist/intentguard.<platform>-<arch>.node files the sibling checkout ships (confirmed
 * byte-for-byte identical build output, C575/C600) — this is the THIRD candidate, after
 * INTENTGUARD_REPO and the sibling checkout, never instead of them (dev checkouts keep working
 * unchanged; only a host with NEITHER falls here).
 *
 * Resolved via createRequire(...).resolve('intentguard/package.json') — the standard node_modules
 * walk from THIS module's own location, so it finds whatever 'intentguard' resolution would hand a
 * plain `require('intentguard')` in the same tree (hoisted to the repo root in a dev install, or
 * nested under node_modules/thetacog-mcp/node_modules/intentguard inside a published, isolated
 * install) — never a hand-rolled path guess. `require` is injectable (same convention as
 * loadNapiAddon's `load` param) so a test can fake "the package is installed" without actually
 * installing one. No sibling, no env var, AND no installed package → null, same as before C601:
 * the caller's own js-fallback branch names the UNMEASURED reason.
 */
export function resolveInstalledNapi({ platform = process.platform, arch = process.arch, require: req = require_ } = {}) {
  let pkgJsonPath;
  try { pkgJsonPath = req.resolve('intentguard/package.json'); }
  catch { return null; }
  const root = dirname(pkgJsonPath);
  const file = resolve(root, 'napi', 'dist', napiFileName(platform, arch));
  return existsSync(file) ? { path: file, source: 'installed' } : null;
}

/**
 * THE RESOLVER: crate (matching host) → napi (matching host) → js-fallback. Always returns a descriptor
 * naming `engine` — one of ENGINES — never a bare path a caller has to infer the engine from.
 */
export function resolveEngine({ platform = process.platform, arch = process.arch, pkgRoot = PKG_ROOT, repo = REPO, env = process.env, intentGuardRoot, require: req = require_ } = {}) {
  const here = `${platform}-${arch}`;
  const ig = intentGuardRoot || INTENTGUARD_ROOT(repo);
  const crate = resolveCrate({ platform, arch, pkgRoot, repo, env });
  if (crate) return { engine: ENGINES.CRATE, path: crate.path, source: crate.source, platform: here };
  const napi = resolveNapi({ platform, arch, repo, intentGuardRoot: ig, require: req });
  if (napi) return { engine: ENGINES.NAPI, path: napi.path, source: napi.source, platform: here };
  const napiChecked = resolve(ig, 'napi', 'dist', napiFileName(platform, arch));
  return {
    engine: ENGINES.JS_FALLBACK,
    path: null,
    platform: here,
    why: `UNMEASURED on ${here}: no on-chip binary header matches it (checked ${resolve(pkgRoot, PKG_CHIP_REL)}, ${resolve(repo, CHECKOUT_CHIP_REL)}, PMU_BINARY) and no IntentGuard napi prebuild at ${napiChecked} or at an installed 'intentguard' package's napi/dist/${napiFileName(platform, arch)} — build .thetacog/pmu (cargo build --release) for ${here}, npm install intentguard, or accept the JS fallback's UNMEASURED reading`,
  };
}

/** loads the napi addon THIS resolver named — never throws. {addon,path} or {addon:null,reason}. */
export function loadNapiAddon(resolved, { load = require_ } = {}) {
  if (!resolved || resolved.engine !== ENGINES.NAPI) {
    return { addon: null, reason: `resolveEngine() did not pick napi (engine: ${resolved && resolved.engine})` };
  }
  try { return { addon: load(resolved.path), path: resolved.path }; }
  catch (e) { return { addon: null, reason: `${resolved.path} failed to load: ${e && e.message ? e.message : e}` }; }
}

/**
 * THE ONE DEMONSTRATED READING — the ballistic placement (the frames JSON `--ballistic` prints), the
 * flag data/vna/linux-fallback-inventory.json (C574) already judges napi-covered with confirmed byte
 * identity. `grid` is a 144 or 20,736-length int array (the on-chip binary's own --grid two accepted shapes);
 * `start` is a ShortLex PAIR label ("A,A", not the bare top-level "A" — ballistic::SHORTLEX is the
 * 144-entry pair table both engines share; an unmatched label walks every occupied anchor instead of
 * one, on either engine, by the shared `start_index`/`.position` miss-is-None contract). Always tags
 * its own `engine`; a js-fallback reading never computes a result and never claims one — it names why.
 */
export function ballisticReading(grid, { start = null, maxDepth = null, decay = null } = {}, resolved = resolveEngine()) {
  if (resolved.engine === ENGINES.CRATE) {
    const args = ['--ballistic', '--grid', '-'];
    if (start != null) args.push('--start', String(start));
    if (maxDepth != null) args.push('--max-depth', String(maxDepth));
    if (decay != null) args.push('--decay', String(decay));
    const out = execFileSync(resolved.path, args, { input: JSON.stringify(grid), encoding: 'utf8', maxBuffer: 1 << 28 });
    return { engine: ENGINES.CRATE, path: resolved.path, frames: JSON.parse(out) };
  }
  if (resolved.engine === ENGINES.NAPI) {
    const { addon, reason } = loadNapiAddon(resolved);
    if (!addon) return { engine: ENGINES.NAPI, frames: null, unmeasured: true, why: reason };
    // C601: a loaded addon with no walk() export (a future/narrower napi build) is named here,
    // never called blind — "pretend it worked" would be a thrown TypeError masquerading as a crash
    // instead of the honest UNMEASURED this module promises everywhere else.
    if (typeof addon.walk !== 'function') {
      return { engine: ENGINES.NAPI, frames: null, unmeasured: true, why: `${resolved.path} loaded but exports no walk() — UNMEASURED, never pretended` };
    }
    const json = addon.walk(grid, start, maxDepth, decay);
    return { engine: ENGINES.NAPI, path: resolved.path, frames: JSON.parse(json) };
  }
  return { engine: ENGINES.JS_FALLBACK, frames: null, unmeasured: true, why: resolved.why || 'no JS ballistic walk exists for the 144×144 lattice' };
}

/**
 * C575 round 2 (coordinator, 2026-10-02): THE DROP-IN FOR data/vna/linux-fallback-inventory.json's
 * (C574) 15 real spawn sites — every one calls `resolvePmuBinary(repoRoot)` once at module or call
 * scope and execs whatever it returns with no header check at all (the exact bug class C569 fixed
 * for only two of them). This swaps in for that bare call: it reuses resolvePmuBinary's OWN broader
 * search (home dir, sibling checkouts — not just this module's own three narrower candidates), then
 * header-checks WHATEVER IT FOUND against this host before handing it back.
 *
 *   · matches this host  → { engine:'crate', path: <the SAME path resolvePmuBinary alone would have
 *     returned> } — BYTE-IDENTICAL behaviour: every existing caller that does `const bin =
 *     resolvePmuBinary(ROOT)` and then execs `bin` gets the identical value, unchanged.
 *   · does not match, AND the caller names `--ballistic` among `flags` (data/vna/linux-fallback-
 *     inventory.json's ONE covered flag with confirmed byte identity, scripts/pmu/rc-compute.mjs's
 *     own call) → { engine:'napi', path: <the real .node> } — the caller should route to
 *     ballisticReading(), never spawn `path` as a binary (there is nothing to spawn: a napi engine
 *     is a require()'d addon, not a file argv0).
 *   · does not match, and no covered flag applies → { engine:'js-fallback', path:null, why:<ONE
 *     UNMEASURED line> } — the SAME single-line contract pmuPlatformLine() already holds for
 *     pipeline.mjs/definer-walk-144.mjs (C569); never present napi's lens() as a `--lens` reading —
 *     `--lens` has no covered route here or anywhere in this module.
 *
 * `path: null` on the fallback is a DELIBERATE improvement, not a behaviour change on a matching
 * host: every one of the 15 call sites already treats resolvePmuBinary's return value as "maybe
 * doesn't exist yet" (its own doc comment: "if none exist we return the primary path so the
 * caller's own existsSync check trips the honest fallback") — today a MISMATCHED-platform file
 * passes that existsSync check and crashes at exec; `null` fails it instead, landing the caller on
 * its OWN already-written "not built" branch rather than a raw OS exec error.
 */
function describeBinary(bin, { flags = [], platform = process.platform, arch = process.arch, repo = REPO } = {}) {
  const here = `${platform}-${arch}`;
  if (bin && existsSync(bin) && runsHere(binaryPlatform(bin), platform, arch)) {
    return { engine: ENGINES.CRATE, path: bin, platform: here };
  }
  if (flags.includes('--ballistic')) {
    const napi = resolveNapi({ platform, arch, repo });
    if (napi) return { engine: ENGINES.NAPI, path: napi.path, platform: here };
  }
  const hdr = bin && existsSync(bin) ? binaryPlatform(bin) : null;
  const uncovered = flags.filter((f) => f !== '--ballistic');
  return {
    engine: ENGINES.JS_FALLBACK,
    path: null,
    platform: here,
    why: `UNMEASURED on ${here}: the on-chip binary at ${bin} is ${hdr ? `built for ${hdr}` : 'absent or unrecognised'}, not ${here}${uncovered.length ? ` — ${uncovered.join(', ')} ${uncovered.length > 1 ? 'have' : 'has'} no napi route (only --ballistic does)` : ''} — build .thetacog/pmu (cargo build --release) for ${here}, or set PMU_BINARY`,
  };
}

export function resolveSpawnBinary(repoRoot, opts = {}) {
  return describeBinary(resolvePmuBinary(repoRoot), { ...opts, repo: opts.repo || repoRoot });
}

/**
 * guardBinary(bin, opts) — THE OTHER HALF of resolveSpawnBinary, for a spawn site that keeps its OWN
 * literal `resolvePmuBinary(repoRoot)` call rather than calling resolveSpawnBinary directly. WHY TWO
 * DOORS: data/vna/linux-fallback-inventory.mjs's spawnSites() (C574) finds a real spawn site by
 * scanning for the LITERAL TEXT `NAME = resolvePmuBinary(` bound to an exec call — a site that
 * instead calls `resolveSpawnBinary(repoRoot, …)` no longer carries that literal and silently drops
 * off the inventory's own re-derive (measured: 13 of these 15 sites did exactly this and turned
 * data/vna/linux-fallback-inventory.json stale against tests/vna/c574-1-…). guardBinary keeps the
 * ORIGINAL `NAME = resolvePmuBinary(repoRoot)` line intact (so the deriver still finds and names the
 * site) and layers the SAME header-check + napi fallback on top as a second statement:
 *   `let NAME = resolvePmuBinary(ROOT); NAME = guardBinary(NAME, { flags: […] });`
 * Returns the SAME string unchanged on a host match (byte-identical), an `{ engine:'napi', path }`
 * OBJECT only when `--ballistic` is in `flags` and a napi prebuild exists (the one call site that
 * needs this, scripts/pmu/rc-compute.mjs, special-cases `typeof result !== 'string'` before using it
 * — passing it straight to execFileSync/existsSync as if it were a path would be exactly the bug this
 * module exists to prevent), or null otherwise — the EXACT value these call sites' own
 * `!bin || !existsSync(bin)` fallback already treats as "not built".
 */
export function guardBinary(bin, opts = {}) {
  const d = describeBinary(bin, opts);
  if (d.engine === ENGINES.CRATE) return d.path;
  if (d.engine === ENGINES.NAPI) return { engine: ENGINES.NAPI, path: d.path };
  return null;
}
