#!/usr/bin/env node
// scripts/vna/forecast-localise.mjs — C610c: THE LOCALISATION BANK. WHICH ROWS, WHICH FILES, WHICH SPANS, WHICH WORDS. LLM-FREE.
//
// A forecast F (C610a's ensemble walk: mean heat per cell, spread per cell across the ingress points) says WHERE a path is likely to
// land. This file names what already sits there, by evidence only:
//   ZONES     the forecast's lit cells, classified and grouped. CONSENSUS = hot and low spread (every ingress agrees the path leans
//             here). CONTESTED = high spread (the ingress points disagree; the walk is telling the reader to look). One zone = one class
//             inside one block of the 3×3 block grid (the A/B/C strip of each half — the same block grid cog.mjs measures radius on);
//             its coordinate is its hottest cell.
//   ROWS      spec rows whose WALKED cells (row.cells — retro-snowball.mjs rowsOf(), the same input the snowball grows over) overlap
//             the zone, ranked by spec-tree.mjs ncd() of the row text to the candidate. Each row carries the overlapping cells.
//   FILES     the files in F_in (the aperture receipt's reality rows) whose C115z spans lit a zone cell, with the span's bytes,
//             lines and chunk_sha. A span's lit cells are read off the span itself (span.cells) or walked by the injected walker
//             over the span's own bytes — never inferred from the file name.
//   WORDS     terms in the candidate that belong to the zone coordinate's vocabulary and NOT to the top row's, read the way
//             splatter.mjs reads data/pmu/snippet-library-144.json (its words / vocabOf / documentFrequency, imported, never copied).
//
// NEVER a regex of body/machine nouns, never a decoded 12×12 standing in for the panel (tests/ops/no-lattice-proxy.test.mjs): every
// cell named here came out of the one Rust walk (the forecast, the tree's walked rows, the span walk) or is refused.
//
// SUFFICIENT FOR: where the zones are, and which declared rows, files and spans sit in them.
// NOT SUFFICIENT FOR: what those areas MEAN — that is the LLM's later knock-on, never this receipt (THE RECEIPT IS LLM-FREE).
// A forecast without an aperture stamp is REFUSED (UNMEASURED), never localised: a reading that cannot say which aperture it was
// taken at cannot be compared to the commit it forecasts.
//
// Rust port row: declared C610c-port — the zone classifier DECIDES (a threshold on spread), so its home is lens.rs beside the
// ensemble walk (zone_classify(mean, spread, HEAT_FLOOR, SPREAD_SPLIT) over the same 144 cells C610a's --ensemble-walk returns).
// data/vna/rust-punch-list.json is GENERATED by scripts/vna/engine-map.mjs, so the declaration lives here and in PORT_ROW.
//
// @guard tests/vna/c610c-the-localisation-bank.test.mjs
import { writeFileSync, mkdirSync, readFileSync, existsSync } from 'node:fs';
import { resolve, dirname, extname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { rowsOf } from './retro-snowball.mjs';
import { ncd } from './spec-tree.mjs';
import { words, library, vocabOf, documentFrequency, DF_CEILING } from './splatter.mjs';

const REPO = process.env.VNA_REPO || resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const OUT_DIR = resolve(REPO, 'data/vna/forecast-localisation');
export const PORT_ROW = 'C610c-port — lens.rs zone_classify(mean, spread, HEAT_FLOOR, SPREAD_SPLIT): the classifier decides, so it moves into the crate beside --ensemble-walk';

// THE CLASSIFIER'S TWO NUMBERS, with their argument. Both are fractions of the forecast's PEAK mean heat, so they do not depend on
// how many hops a walk spent. A cell is HOT when its mean is at least half the peak (the upper half of what the ensemble lit).
// A cell is CONTESTED when the ingress points disagree about it by more than a quarter of the peak — past that the disagreement is
// larger than half the gap between "hot" and "the peak", so the mean alone would mislead. Lit-but-cool cells with low spread are
// neither: the ensemble agrees nothing much happens there. Declared, never tuned; the port moves them into the crate unchanged.
export const HEAT_FLOOR = 0.5, SPREAD_SPLIT = 0.25;
export const MAX_BLOCK_LINES = 12;   // header (label + aperture stamp) + at most 11 zone lines
export const SUFFICIENT_FOR = 'where the zones are, and which declared rows, files and spans sit in them — every name carries its lit-cell evidence';
export const NOT_SUFFICIENT_FOR = 'what those areas mean: that is the LLM\'s later knock-on, never this receipt (THE RECEIPT IS LLM-FREE); nor whether the path is good (Rice)';

const blockOf = (cell) => { const [r, c] = String(cell).split(','); const b = (x) => String(x || '').replace(/\d+$/, ''); return `${b(r)}×${b(c)}`; };

// F.mean / F.spread: an object keyed by coordinate, or an array of 144 in F.coords' order (C610a's heat order). An array with no
// coords is read in definer-walk-144.mjs COORDS order, imported only then (that module resolves the binary at load).
async function cellMap(v, coords) {
  if (!v) return new Map();
  if (Array.isArray(v)) {
    const C = coords || (await import('../pmu/definer-walk-144.mjs')).COORDS;
    return new Map(v.map((x, i) => [C[i], Number(x) || 0]).filter(([c]) => c));
  }
  return new Map(Object.entries(v).map(([c, x]) => [c, Number(x) || 0]));
}

// THE CLASSIFIER (decides — port row C610c-port). Returns { consensus: [cell], contested: [cell] } with the per-cell numbers.
export function classifyCells(mean, spread, { heatFloor = HEAT_FLOOR, spreadSplit = SPREAD_SPLIT } = {}) {
  const peak = Math.max(0, ...mean.values());
  const out = { peak, cells: [] };
  if (!(peak > 0)) return out;
  for (const [cell, m] of mean) {
    if (!(m > 0)) continue;
    const s = spread.get(cell) || 0;
    const cls = s / peak > spreadSplit ? 'contested' : m / peak >= heatFloor ? 'consensus' : null;
    if (cls) out.cells.push({ cell, cls, heat: +(m / peak).toFixed(4), spread: +(s / peak).toFixed(4) });
  }
  return out;
}

export function zonesOf(classified) {
  const by = new Map();
  for (const c of classified.cells) {
    const k = `${c.cls}:${blockOf(c.cell)}`;
    if (!by.has(k)) by.set(k, { cls: c.cls, block: blockOf(c.cell), cells: [] });
    by.get(k).cells.push(c);
  }
  return [...by.values()].map((z) => {
    z.cells.sort((a, b) => (b.heat - a.heat) || (a.cell < b.cell ? -1 : 1));
    return { id: `${z.cls === 'consensus' ? 'CONS' : 'CONT'} ${z.block}`, class: z.cls, block: z.block, coord: z.cells[0].cell, peak_heat: z.cells[0].heat, max_spread: Math.max(...z.cells.map((c) => c.spread)), cells: z.cells.map((c) => c.cell), cell_stats: z.cells };
  }).sort((a, b) => (a.class === b.class ? 0 : a.class === 'consensus' ? -1 : 1) || (b.peak_heat - a.peak_heat) || (a.id < b.id ? -1 : 1));
}

const sha256 = (b) => createHash('sha256').update(b).digest('hex');

/**
 * localise({ forecast, tree, rows, fIn, walkSpan, lib }) — pure over its inputs except the injected walker.
 *   forecast  { label, aperture_version, mean, spread, coords?, ingress?, candidate, declared? }  (C610a output + the candidate text)
 *   tree      the spec tree ({nodes}) — rows = retro-snowball rowsOf(tree); or pass rows [{id, cells, text, pixel}] directly
 *   fIn       F_in: [{ path, blob?, spans: [{ bytes, lines, chunk_sha, cells? }] }] (aperture-receipt.mjs reality.rows)
 *   walkSpan  (path, span) → cells[] | null, for spans that do not carry their own cells (the live CLI walks the span bytes)
 */
export async function localise({ forecast, tree = null, rows = null, fIn = [], walkSpan = null, lib = undefined, maxRows = 4, maxFiles = 4, maxWords = 6 } = {}) {
  const F = forecast || {};
  const label = String(F.label || 'unlabelled');
  if (!F.aperture_version) return { label, refused: true, verdict: 'UNMEASURED', why: 'the forecast carries no aperture_version — a reading that cannot name its aperture cannot be scored against the commit it forecasts', sufficient_for: SUFFICIENT_FOR, not_sufficient_for: NOT_SUFFICIENT_FOR };
  const mean = await cellMap(F.mean, F.coords), spread = await cellMap(F.spread, F.coords);
  const zones = zonesOf(classifyCells(mean, spread));
  const R = rows || rowsOf(tree);
  const cand = String(F.candidate || '');
  const candLow = cand.toLowerCase();
  const memo = new Map();
  const dist = (r) => { if (!memo.has(r.id)) memo.set(r.id, cand ? +ncd(candLow, String(r.text || '').toLowerCase()).toFixed(4) : null); return memo.get(r.id); };

  // the span cells, walked at most once per span
  const spanCells = new Map();
  const cellsOfSpan = (file, span) => {
    const k = `${file.path}@${span.chunk_sha || JSON.stringify(span.bytes)}`;
    if (!spanCells.has(k)) {
      let c = Array.isArray(span.cells) ? span.cells : null; let via = c ? 'span.cells' : null;
      if (!c && walkSpan) { try { c = walkSpan(file.path, span); via = 'walked'; } catch { c = null; } }
      spanCells.set(k, { cells: Array.isArray(c) ? c : null, via: Array.isArray(c) ? via : 'unwalked' });
    }
    return spanCells.get(k);
  };

  const L = lib === undefined ? library() : lib;
  const dfr = L ? documentFrequency(L) : null;
  const distinctive = (w) => !dfr || (dfr.df.get(w) || 0) <= Math.max(1, Math.floor(dfr.n * DF_CEILING));
  const said = words(cand);

  for (const z of zones) {
    const Z = new Set(z.cells);
    z.rows = R.map((r) => ({ id: r.id, node: r.node || null, pixel: r.pixel || null, ncd: dist(r), lit: (r.cells || []).filter((c) => Z.has(c)) }))
      .filter((r) => r.lit.length)
      .sort((a, b) => ((a.ncd ?? 9) - (b.ncd ?? 9)) || (b.lit.length - a.lit.length) || (a.id < b.id ? -1 : 1))
      .slice(0, maxRows);
    z.files = [];
    for (const f of fIn || []) {
      const spans = [];
      for (const s of f.spans || []) {
        const sc = cellsOfSpan(f, s);
        const lit = (sc.cells || []).filter((c) => Z.has(c));
        if (lit.length) spans.push({ bytes: s.bytes || null, lines: s.lines || null, chunk_sha: s.chunk_sha || null, via: sc.via, lit });
      }
      if (spans.length) z.files.push({ path: f.path, blob: f.blob || null, spans });
    }
    z.files = z.files.slice(0, maxFiles);
    const rowCoord = (z.rows[0] && z.rows[0].pixel) || F.declared || null;
    const zoneV = L ? vocabOf(L, z.coord) : new Set();
    const rowV = L && rowCoord ? vocabOf(L, rowCoord) : new Set();
    z.words = { against: rowCoord, terms: [...zoneV].filter((w) => said.has(w) && !rowV.has(w) && distinctive(w)).sort((a, b) => ((dfr?.df.get(a) || 0) - (dfr?.df.get(b) || 0)) || (a < b ? -1 : 1)).slice(0, maxWords) };
    delete z.cell_stats;
  }

  const out = {
    v: 1, at: new Date().toISOString(), label, aperture_version: F.aperture_version, engine: 'forecast-localise.mjs — set overlap on walked cells, gzip-NCD rank, splatter vocabulary; zero LLM',
    thresholds: { HEAT_FLOOR, SPREAD_SPLIT, of: 'fractions of the forecast peak mean heat' }, port_row: PORT_ROW,
    ingress: F.ingress || null, candidate_chars: cand.length, rows_considered: R.length, files_considered: (fIn || []).length,
    span_walks: [...spanCells.entries()].map(([k, v]) => ({ span: k, via: v.via, cells: v.cells ? v.cells.length : null })),
    zones, sufficient_for: SUFFICIENT_FOR, not_sufficient_for: NOT_SUFFICIENT_FOR,
  };
  out.block = blockText(out);
  return out;
}

const spanStr = (s) => (Array.isArray(s.lines) && s.lines.length ? s.lines.map((l) => (l[0] === l[1] ? `L${l[0]}` : `L${l[0]}-${l[1]}`)).join(',') : s.bytes ? `b${s.bytes[0]}-${s.bytes[1]}` : '?') + (s.chunk_sha ? `#${s.chunk_sha.slice(0, 8)}` : '');

export function blockText(r) {
  if (r.refused) return [`C610c localisation · ${r.label} · ${r.verdict} — ${r.why}`];
  const head = `C610c localisation · ${r.label} · aperture ${r.aperture_version} · ${r.zones.length} zone(s) · LLM-free: where, never what it means`;
  const lines = r.zones.slice(0, MAX_BLOCK_LINES - 1).map((z) => {
    const rows = z.rows.length ? z.rows.map((x) => x.id).join(',') : '—';
    const files = z.files.length ? z.files.map((f) => `${f.path}:${f.spans.map(spanStr).join(',')}`).join(' ') : '—';
    const w = z.words.terms.length ? z.words.terms.join(',') : '—';
    return `${z.id} @${z.coord} (${z.cells.length} cells) → rows ${rows} · files ${files} · words ${w}`;
  });
  if (r.zones.length > MAX_BLOCK_LINES - 1) lines[lines.length - 1] += ` (+${r.zones.length - (MAX_BLOCK_LINES - 1)} more zones in the JSON)`;
  return [head, ...lines];
}

export function writeLocalisation(r, { dir = OUT_DIR } = {}) {
  mkdirSync(dir, { recursive: true });
  const p = join(dir, `${String(r.label).replace(/[^A-Za-z0-9._-]/g, '_')}.json`);
  writeFileSync(p, JSON.stringify(r, null, 2) + '\n');
  return p;
}

// ── the live door: a commit's own Δ panel as a single-ingress forecast ─────────────────────────────────────────────────────────
// Until C610a's ensemble lands, the one forecast-shaped reading on disk is the aperture receipt's Δ: the cells the one Rust walk
// lit for the commit (in_lane · adjacent · off_lane). Read as K = 1 (spread 0), every lit cell is CONSENSUS by construction — the
// receipt says so (ingress: 'receipt-delta, K=1'). The span bytes are recovered from the IMMUTABLE commit (git show <sha>:<path>,
// W3), through corpus-ingest.mjs commentProseWithSpans for code (the C115z prose space), and are walked ONLY when their sha256
// equals the receipt's chunk_sha — a mismatch reads 'unwalked', never a guess.
export async function forecastFromReceipt(receipt) {
  const d = receipt.delta || {};
  const cells = [...new Set([...(d.in_lane || []), ...(d.adjacent || []), ...(d.off_lane || [])])];
  const mean = Object.fromEntries(cells.map((c) => [c, 1])); const spread = Object.fromEntries(cells.map((c) => [c, 0]));
  return { mean, spread, ingress: { rule: 'receipt-delta', K: 1 }, aperture_version: receipt.aperture_version || null };
}

async function liveWalkSpan(sha) {
  const { execFileSync } = await import('node:child_process');
  const { commentProseWithSpans } = await import('../pmu/corpus-ingest.mjs');
  const { lensWalk } = await import('../../src/lib/pmu/walk-door.mjs');
  const { mkdtempSync } = await import('node:fs'); const { tmpdir } = await import('node:os');
  const scratch = mkdtempSync(join(tmpdir(), 'c610c-'));
  return (path, span) => {
    if (!span || !Array.isArray(span.bytes)) return null;
    let raw; try { raw = execFileSync('git', ['show', `${sha}:${path}`], { cwd: REPO, maxBuffer: 1 << 28 }).toString('utf8'); } catch { return null; }
    const prose = commentProseWithSpans(raw, extname(path)).text;
    const buf = Buffer.from(prose || raw, 'utf8').subarray(span.bytes[0], span.bytes[1]);
    if (span.chunk_sha && sha256(buf) !== span.chunk_sha) return null;
    const { row } = lensWalk(buf.toString('utf8'), { source: 'probe', ref: 'c610c-span', tape: join(scratch, 'probe-tape.ndjson'), receiptsDir: join(scratch, 'receipts'), timeoutMs: 6000 });
    return row && row.pixel ? (row.cells || []) : null;
  };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const arg = (k, d = null) => { const i = process.argv.indexOf(k); return i >= 0 ? process.argv[i + 1] : d; };
  const rPath = resolve(REPO, arg('--from-receipt', 'data/vna/aperture-receipt.json'));
  if (!existsSync(rPath)) { console.error(`no aperture receipt at ${rPath} — node scripts/vna/aperture-receipt.mjs`); process.exit(2); }
  const receipt = JSON.parse(readFileSync(rPath, 'utf8'));
  const sha = receipt.commit;
  const { execFileSync } = await import('node:child_process');
  const candidate = arg('--candidate') || (sha ? execFileSync('git', ['log', '-1', '--pretty=%B', sha], { cwd: REPO }).toString() : '');
  const F = { ...(await forecastFromReceipt(receipt)), label: arg('--label', `delta-${String(sha || 'preview').slice(0, 10)}`), candidate };
  const { readTree, TREE } = await import('./spec-tree.mjs');
  const tree = readTree(TREE, { text: true });
  const r = await localise({ forecast: F, tree, fIn: (receipt.reality && receipt.reality.rows) || [], walkSpan: sha ? await liveWalkSpan(sha) : null });
  if (!process.argv.includes('--no-write') && !r.refused) console.error(`wrote ${writeLocalisation(r)}`);
  console.log((r.block || blockText(r)).join('\n'));
}
